import fs from 'node:fs';
import { expect, test } from '@playwright/test';

test('Phase 5: demo data → AUTO forecast → chart + accuracy → override → export CSV', async ({
  page,
}) => {
  const stamp = Date.now();
  await page.goto('/signup');
  await page.getByLabel('Company name').fill(`Phase5 Co ${stamp}`);
  await page.getByLabel('Your name').fill('Fran Owner');
  await page.getByLabel('Email').fill(`p5-${stamp}@example.com`);
  await page.getByLabel('Password').fill('Password123');
  await page.getByRole('button', { name: 'Sign up' }).click();
  await page.getByRole('button', { name: 'Load demo data' }).click();
  await expect(page.getByText(/Demo data loaded/)).toBeVisible({ timeout: 30_000 });

  // Start an automatic forecast run; it finishes in the background.
  await page.getByRole('link', { name: 'Forecasts' }).click();
  await expect(page.getByTestId('no-runs')).toBeVisible();
  await page.getByLabel('Horizon (weeks)').fill('26');
  await page.getByRole('button', { name: 'Run forecast' }).click();
  await expect(page.getByText('Forecast run started')).toBeVisible();
  const row = page.locator('[data-testid^="run-"]').first();
  await expect(row).toContainText('DONE', { timeout: 60000 });
  await expect(row).toContainText('16/16');
  await row.getByRole('link').click();

  // Accuracy table: one row per product/location, with a model per series.
  await expect(page.getByTestId('run-summary')).toContainText(
    '26 weeks · automatic model selection · 16/16 series',
  );
  const accuracy = page.getByTestId('accuracy-table');
  await expect(accuracy.locator('tbody tr')).toHaveCount(16);
  await expect(accuracy).toContainText('Holt-Winters (seasonal)'); // seasonal demo products
  await expect(accuracy).toContainText('Croston (intermittent)'); // the sparse tin
  await accuracy.getByRole('button', { name: 'Sort by SKU' }).click();
  await expect(accuracy.locator('tbody tr').first()).toContainText(/\w/);

  // Chart for a product/location, then its numbers in the table view.
  await page.getByTestId('acc-GFT-BOX-WH-EAST').click();
  const summary = page.getByTestId('series-summary');
  await expect(summary).toContainText('GFT-BOX');
  await expect(summary).toContainText('WH-EAST');
  await expect(summary).toContainText('WAPE');
  await expect(
    page.getByRole('img', { name: 'History, forecast and prediction interval chart' }),
  ).toBeVisible();
  await page.getByRole('button', { name: 'View as table' }).click();
  const table = page.getByTestId('series-table');
  await expect(table.locator('tbody tr')).toHaveCount(26);
  const firstWeek = (
    await table.locator('tbody tr').first().locator('td').first().innerText()
  ).trim();
  const firstForecast = (
    await table.locator('tbody tr').first().locator('td').nth(1).innerText()
  ).trim();

  // Override a week: a reason is required, then it shows in a different colour with the final value.
  await page.getByRole('button', { name: 'Show chart' }).click();
  const form = page.getByRole('form', { name: 'Add override' });
  await form.getByLabel('Week').selectOption(firstWeek);
  await form.getByLabel('Quantity').fill('777');
  await form.getByRole('button', { name: 'Override' }).click(); // blocked by the required reason
  await expect(page.getByTestId('overrides')).toHaveCount(0);
  await form.getByLabel('Reason (required)').fill('Holiday promotion');
  await form.getByRole('button', { name: 'Override' }).click();
  await expect(page.getByText('Override saved')).toBeVisible();
  await expect(page.getByTestId(`override-${firstWeek}`)).toContainText('777');
  await page.getByRole('button', { name: 'View as table' }).click();
  const overridden = page.getByTestId(`fc-${firstWeek}`);
  await expect(overridden).toContainText('777');
  await expect(overridden).toContainText(firstForecast); // the model forecast is kept next to the override

  // Export CSV (generated by the API) matches the data and includes the override.
  const [download] = await Promise.all([
    page.waitForEvent('download'),
    page.getByRole('button', { name: 'Export CSV' }).click(),
  ]);
  const text = fs.readFileSync((await download.path())!, 'utf8');
  const lines = text.trim().split('\n');
  expect(lines[0]).toBe(
    'sku,location_code,week_start,forecast,lower,upper,override,final,model_used',
  );
  expect(lines).toHaveLength(1 + 16 * 26);
  const overrideLine = lines.find((l) => l.startsWith('GFT-BOX,WH-EAST,' + firstWeek))!;
  expect(overrideLine.split(',')[6]).toBe('777');
  expect(overrideLine.split(',')[7]).toBe('777.00');

  // The override can be removed again.
  await page.getByRole('button', { name: `Remove override ${firstWeek}` }).click();
  await expect(page.getByTestId(`override-${firstWeek}`)).toHaveCount(0);
});
