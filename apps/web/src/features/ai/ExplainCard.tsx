import { useState } from 'react';
import { useMutation } from '@tanstack/react-query';
import { Can } from '../auth/Can';
import { Notice, errText } from '../../components/ui';
import { aiApi } from './api';

const CONF_CLS = {
  LOW: 'bg-red-100 text-red-800',
  MEDIUM: 'bg-amber-100 text-amber-800',
  HIGH: 'bg-green-100 text-green-800',
} as const;

/** "Explain this forecast" for the selected product/location of a run. */
export function ExplainCard({
  runId,
  productId,
  locationId,
}: {
  runId: string;
  productId: string;
  locationId: string;
}) {
  const [shown, setShown] = useState<{
    key: string;
    data: Awaited<ReturnType<typeof aiApi.explain>>;
  } | null>(null);
  const key = `${runId}|${productId}|${locationId}`;
  const explain = useMutation({
    mutationFn: () => aiApi.explain({ runId, productId, ...(locationId && { locationId }) }),
    onSuccess: (data) => setShown({ key, data }),
  });
  const current = shown?.key === key ? shown.data : null;
  return (
    <Can permission="ai:use">
      <div className="space-y-2 border-t pt-3">
        <button
          onClick={() => explain.mutate()}
          disabled={explain.isPending}
          className="rounded border border-purple-300 bg-purple-50 px-3 py-1.5 text-sm text-purple-900 disabled:opacity-60"
        >
          {explain.isPending ? 'Explaining…' : 'Explain this forecast'}
        </button>
        {explain.isError && <Notice kind="error">{errText(explain.error)}</Notice>}
        {current && (
          <div
            className="rounded-lg border border-purple-200 bg-purple-50/40 p-3 text-sm"
            data-testid="explanation"
          >
            <div className="mb-1 flex items-center gap-2">
              <strong>AI explanation</strong>
              <span
                className={`rounded px-2 py-0.5 text-xs font-medium ${CONF_CLS[current.result.confidence]}`}
                data-testid="confidence"
              >
                Confidence: {current.result.confidence}
              </span>
              {current.cached && (
                <span className="text-xs text-gray-500" data-testid="cached">
                  saved — no quota used
                </span>
              )}
            </div>
            <p>{current.result.explanation}</p>
            <p className="mt-2 font-medium">Main drivers</p>
            <ul className="list-disc pl-5">
              {current.result.drivers.map((d, i) => (
                <li key={i}>{d}</li>
              ))}
            </ul>
            {current.result.caveats.length > 0 && (
              <>
                <p className="mt-2 font-medium">Caveats</p>
                <ul className="list-disc pl-5 text-gray-700">
                  {current.result.caveats.map((d, i) => (
                    <li key={i}>{d}</li>
                  ))}
                </ul>
              </>
            )}
            <p className="mt-2 text-xs text-gray-500">
              Generated by AI from your aggregated numbers; double-check before acting.
            </p>
          </div>
        )}
      </div>
    </Can>
  );
}
